import 'package:mandarin_g2p/src/cn2an.dart';
import 'package:test/test.dart';

/// Expected values are cn2an 0.5.24's own `transform(text, 'an2cn')`,
/// run on 13 Nov 2026.
void main() {
  const cases = {
    '2019年3月5日': '二零一九年三月五日',
    '共3/4的人': '共四分之三的人',
    '增长了12.5%': '增长了百分之十二点五',
    '气温-3℃': '气温-三摄氏度',
    '1,000,000': '一,零,零',
    '13800138000': '一百三十八亿零一十三万八千',
    '3-5个': '三到五个',
    '2010-2015年': '二千零一十-二零一五年',
    '12345678901234567': '12345678901234567',
    '１２３': '一百二十三',
    '0.5': '零点五',
    '007': '七',
    '10': '十',
    '10010': '一万零一十',
    '100000': '十万',
    '1000000001': '十亿零一',
    '20世纪90年代': '二十世纪九零年代',
    '第1名': '第一名',
    '约有1.25亿': '约有一点二五亿',
    '-12': '负十二',
    '5.': '五.',
    '12345年': '一二三四五年',
    '１２月': '十二月',
    '٣٤': '٣٤',
  };
  for (final e in cases.entries) {
    test('an2cn ${e.key}', () {
      expect(an2cnTransform(e.key), e.value);
    });
  }
}
