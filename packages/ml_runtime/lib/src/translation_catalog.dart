/// The translation pairs (ADR-0008 "Babel", ADR-0014, Trellis 1.5.5):
/// English on one end of every pair (hub and spoke), each a Marian
/// (Helsinki-NLP OPUS-MT) model as an int8 ONNX export. Pinned the same
/// way as the rest of the registry: the two ONNX graphs from Hugging
/// Face's tree API (`lfs.oid`, a method checked three times against real
/// downloads, docs/reference/mt-models.md), the small tokenizer and
/// config files downloaded and hashed. Fetched 2026-10-25. Every URL
/// names the repo's commit rather than `main`, so a re-export upstream
/// can't break a pinned hash and strand a language.
///
/// The first six are the pairs shipped before 1.5.5, from onnx-community.
/// Every later pair is Xenova's export: the same optimum merged-decoder
/// shape (checked by running en-ROMANCE for real), with a merged decoder
/// about a third the size, so a direction costs about 115 MB instead of
/// about 230-250 MB. Since 1.5.9 the first six take Xenova's decoder too
/// (pinned 2026-11-06), after greedy decoding over 50 sentences matched
/// onnx-community's on 90-98% of them, chrF 98.6-99.9 (Task 5's parity
/// check, cited in the 1.5.9 ADR). They keep onnx-community's encoder,
/// tokenizer and configs, which a phone already has, so it fetches only
/// the new decoder; the decoder keeps its file name, and the store
/// prunes the old one by its size (DiskModelStore.pruneUnreferenced).
///
/// `licenses` names the license of the weights: onnx-community's own
/// cards say CC-BY-4.0; Xenova's cards carry none, so the upstream
/// Helsinki-NLP card's license is recorded instead.
///
/// Two pairs are not OPUS-MT and have no third-party export: English to
/// Japanese and Japanese to English are ElanMT-BT (CC BY-SA 4.0), Marian
/// models of the same shape, converted to int8 ONNX by Trellis itself
/// ([_convertedFrom]). Japanese to English replaced opus-mt-ja-en
/// (2026-11-11): on 300 NTREX lines it scored BLEU 19.16, chrF 49.67,
/// against 13.32 and 42.05 (docs/reference/mt-models.md).
///
/// Trellis 1.6.13 (pinned 2026-11-12) adds 37 pairs, each run once for
/// real before it was pinned. Most are single-language Xenova exports.
/// Some reuse a multi-language model under their own id: ro, ca and gl
/// to English on ROMANCE-en, en to ca and gl on en-ROMANCE, lt and lv to
/// English on bat-en, hr, mk, eo, ml and sl to English on mul-en, en to
/// eo and ga on en-mul (`>>epo<<`, `>>gle<<`). The mul pairs are the ones
/// whose three test sentences all came out right; the rest are listed as
/// not registered in docs/reference/mt-models.md. The store keeps files
/// per id, so two such pairs on one phone hold two copies.
/// English to Turkish is onnx-community's tc-big export, about 534 MB,
/// since the small en-trk model scores far lower on news text.
