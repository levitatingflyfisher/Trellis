/// Every pair as a [ModelSpec]. A multi-target export (en-ROMANCE,
/// en-zh, en-ar) is told which language to write by its `>>xx<<` token,
/// carried on the layout; the engine fails closed if the vocab lacks it.
List<ModelSpec> translationCatalog() => [
      for (final (id, source, target, token, license, files) in _pairs)
        ModelSpec(
          id: id,
          task: ModelTask.translation,
          files: [
            for (final (url, sha256, bytes) in files)
              ModelFile(url: url, sha256: sha256, bytes: bytes),
          ],
          licenses: [license],
          // T1, not T2: an int8 Marian pair is a phone-sized download, and
          // the app has no tier probe, so it runs every device at T1. At T2
          // the Translate sheet could never see a pair the Models screen
          // had just downloaded (1.5.6).
          minTier: DeviceTier.t1,
          langs: {target},
          sourceLang: source,
          marianLayout: MarianModelLayout(
            encoderFileName: 'encoder_model_quantized.onnx',
            decoderMergedFileName: 'decoder_model_merged_quantized.onnx',
            sourceSpmFileName: 'source.spm',
            vocabFileName: 'vocab.json',
            configFileName: 'config.json',
            tokenizerConfigFileName: 'tokenizer_config.json',
            targetToken: token,
          ),
        ),
    ];
